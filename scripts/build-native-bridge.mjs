import { execFile } from "node:child_process"
import { chmod, copyFile, mkdir, writeFile } from "node:fs/promises"
import { join, resolve } from "node:path"
import { promisify } from "node:util"
import * as wire from "../src/resident/native-wire.ts"

const runFile = promisify(execFile)
const source = resolve("native/stdio")
const destination = resolve("dist/native")
const generated = `// Code generated by scripts/build-native-bridge.mjs; DO NOT EDIT.
package main

${Object.entries(wire).map(([key, value]) => `const ${key} = ${JSON.stringify(value)}`).join("\n")}
`
await writeFile(join(source, "protocol.generated.go"), generated)
const platforms = ["linux", "darwin"]
const architectures = ["arm64", "amd64"]
await mkdir(destination, { recursive: true })
await copyFile(join(source, "GO-LICENSE"), join(destination, "GO-LICENSE"))
await chmod(join(destination, "GO-LICENSE"), 0o644)
const binaries = platforms.flatMap((platform) => architectures.map((architecture) => ({
  platform,
  architecture,
  path: join(destination, `huly-stdio-${platform}-${architecture === "amd64" ? "x64" : architecture}`)
})))
await Promise.all(binaries.map(async ({ platform, architecture, path }) => {
    await runFile(process.env.HULY_GO_EXECUTABLE ?? "go", ["build", "-trimpath", "-buildvcs=false", "-ldflags=-s -w", "-o", path, "."], {
      cwd: source,
      env: { ...process.env, CGO_ENABLED: "0", GOOS: platform, GOARCH: architecture, GOMAXPROCS: "2" },
      maxBuffer: 1024 * 1024
    })
    await chmod(path, 0o755)
  }))
