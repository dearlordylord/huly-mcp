import { execFile } from "node:child_process"
import { chmod, copyFile, mkdir, readFile, writeFile } from "node:fs/promises"
import { join, resolve } from "node:path"
import { promisify } from "node:util"
import * as wire from "../src/resident/native-wire.ts"
import { MAX_ADAPTER_REQUESTS, MAX_ADAPTER_RESPONSE_BYTES } from "../src/resident/adapter-limits.ts"

const runFile = promisify(execFile)
const source = resolve("native/stdio")
const destination = resolve("dist/native")
const constantType = (key, value) => {
  if (typeof value === "string") return "&str"
  if (key === "NATIVE_ACK") return "u8"
  if (key === "NATIVE_CONTROL_FD") return "i32"
  if (key === "NATIVE_DIAGNOSTIC_FLAG") return "u32"
  return key.endsWith("_MILLIS") ? "u64" : "usize"
}
const generated = `// Generated by scripts/build-native-bridge.mjs; do not edit.\n${
  Object.entries({ ...wire, NATIVE_METADATA_REQUESTS: MAX_ADAPTER_REQUESTS, NATIVE_METADATA_REPLY_BYTES: MAX_ADAPTER_RESPONSE_BYTES }).map(([key, value]) => `pub const ${key}: ${constantType(key, value)} = ${JSON.stringify(value)};`).join("\n")
}\n`
const wirePath = join(source, "src/wire.rs")
if (await readFile(wirePath, "utf8").catch((error) => {
  if (error.code === "ENOENT") return undefined
  throw error
}) !== generated) await writeFile(wirePath, generated)
const targets = [
  { target: "aarch64-unknown-linux-musl", platform: "linux", architecture: "arm64" },
  { target: "x86_64-unknown-linux-musl", platform: "linux", architecture: "x64" },
  { target: "aarch64-apple-darwin", platform: "darwin", architecture: "arm64" },
  { target: "x86_64-apple-darwin", platform: "darwin", architecture: "x64" }
]
await runFile("bash", [resolve("scripts/setup-native-toolchain.sh"), "--cargo", "zigbuild", "--release", "--locked", ...targets.flatMap(({ target }) => ["--target", target])], {
  cwd: source,
  env: { ...process.env, CARGO_INCREMENTAL: "0" },
  maxBuffer: 1024 * 1024
})
await mkdir(destination, { recursive: true })
for (const { target, platform, architecture } of targets) {
  const output = join(destination, `huly-stdio-${platform}-${architecture}`)
  await copyFile(join(source, "target", target, "release/huly-stdio"), output)
  await chmod(output, 0o755)
}
await copyFile(join(source, "THIRD-PARTY-NOTICES"), join(destination, "THIRD-PARTY-NOTICES"))
await chmod(join(destination, "THIRD-PARTY-NOTICES"), 0o644)
