import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { gzipSync, gunzipSync } from "node:zlib"
import { Schema } from "effect"
import { NonEmptyString } from "../src/domain/schemas/shared.js"
import { allTools, toolGroups } from "../src/mcp/tools/eager.js"

const argumentsOffset = 2
const argumentsList = Schema.decodeUnknownSync(Schema.Array(Schema.Literal("--check")))(
  process.argv.slice(argumentsOffset)
)
const check = argumentsList.includes("--check")
const GroupImportSchema = Schema.Struct({ name: NonEmptyString, modulePath: NonEmptyString })
const source = readFileSync("src/mcp/tools/eager.ts", "utf8")
const imports = [...source.matchAll(/import \{ (\w+Tools) \} from "(\.\/[a-z-]+\.js)"/g)].map((match) =>
  Schema.decodeUnknownSync(GroupImportSchema)({ name: match[1], modulePath: match[2] })
)
if (imports.length !== Object.keys(toolGroups).length || imports.some(({ name }) => !Object.hasOwn(toolGroups, name)))
  throw new Error("Every authoring tool group must have one direct named import")
const groupByTool = new Map(
  Object.entries(toolGroups).flatMap(([group, tools]) => tools.map((tool) => [tool.name, group] as const))
)
if (groupByTool.size !== allTools.length) throw new Error("Tool groups must cover every unique operation")
const catalog = allTools.map(({ handler: _handler, operation: _operation, ...definition }) => ({
  group: Schema.decodeUnknownSync(NonEmptyString)(groupByTool.get(definition.name)),
  ...definition
}))
const loaders = `// Generated by pnpm update-tool-catalog; do not edit.\nimport { makeToolGroupLoader } from "../lazy-tool.js"\nexport const toolGroupLoaders = {\n${imports.map(({ modulePath, name }) => `  ${name}: makeToolGroupLoader(() => import(${JSON.stringify(modulePath)}).then(module => module.${name}))`).join(",\n")}\n}\nexport type ToolGroupName = keyof typeof toolGroupLoaders\n`
const catalogText = JSON.stringify(catalog)
const catalogFile = "src/mcp/tools/catalog.json"
const CatalogEnvelopeSchema = Schema.Struct({ encoding: Schema.Literal("gzip-base64"), data: NonEmptyString })
if (check) {
  const envelope = Schema.decodeUnknownSync(Schema.fromJsonString(CatalogEnvelopeSchema))(
    readFileSync(catalogFile, "utf8")
  )
  if (gunzipSync(Buffer.from(envelope.data, "base64")).toString("utf8") !== catalogText)
    throw new Error(`Stale ${catalogFile}; run pnpm update-tool-catalog`)
} else {
  writeFileSync(
    catalogFile,
    JSON.stringify({ encoding: "gzip-base64", data: gzipSync(catalogText, { level: 9 }).toString("base64") }) + "\n"
  )
}
const outputs = new Map([
  [
    "src/mcp/tools/group-loaders.ts",
    execFileSync("pnpm", ["exec", "dprint", "fmt", "--stdin", "src/mcp/tools/group-loaders.ts"], {
      input: loaders,
      encoding: "utf8"
    })
  ]
])
for (const [file, content] of outputs) {
  if (check) {
    if (readFileSync(file, "utf8") !== content) throw new Error(`Stale ${file}; run pnpm update-tool-catalog`)
  } else {
    writeFileSync(file, content)
  }
}
